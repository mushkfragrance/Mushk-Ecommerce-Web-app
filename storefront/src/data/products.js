function variants(baseSku, sizes, { basePrice, onSale, stockOffset = 0 }) {
  const multipliers = {
    '3ml': 0.18,
    '6ml': 0.32,
    '12ml': 0.55,
    '30ml': 1,
    '50ml': 1.55,
    '100ml': 2.6,
  }

  return sizes.map((size, index) => {
    const listPrice = Math.round(basePrice * (multipliers[size] || 1))
    const discounted = onSale && index % 2 === 0
    const price = discounted ? Math.round(listPrice * 0.82) : listPrice
    return {
      size,
      sku: `${baseSku}-${size.replace('ml', '')}`,
      price,
      compareAtPrice: discounted ? listPrice : null,
      salePrice: discounted ? price : null,
      stock: Math.max(0, 40 - index * 6 + stockOffset),
    }
  })
}

function makeProduct(config) {
  const sizeList = config.sizes || ['12ml', '30ml', '50ml', '100ml']

  return {
    id: config.id,
    name: config.name,
    slug: config.slug,
    sku: config.sku,
    shortDescription: config.shortDescription,
    description: config.description,
    brand: 'Mushk Fragrance',
    category: config.category,
    gender: config.gender,
    fragranceFamily: config.fragranceFamily,
    topNotes: config.topNotes,
    middleNotes: config.middleNotes,
    baseNotes: config.baseNotes,
    variants: variants(config.sku, sizeList, {
      basePrice: config.basePrice,
      onSale: config.onSale,
      stockOffset: config.stockOffset || 0,
    }),
    images: config.images,
    featured: Boolean(config.featured),
    bestSeller: Boolean(config.bestSeller),
    newArrival: Boolean(config.newArrival),
    onSale: Boolean(config.onSale),
    rating: config.rating,
    reviewCount: config.reviewCount,
    occasion: config.occasion,
    longevity: config.longevity,
    sillage: config.sillage,
    ingredients: config.ingredients,
    createdAt: config.createdAt,
    popularity: config.popularity,
  }
}

